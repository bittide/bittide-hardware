//! Programs the IPMI FRU EEPROM of the Trenz TEF0008 FMC card on the FMC HPC
//! connector of a KCU105. See `Bittide.Instances.Hitl.FmcEeprom` for why, and
//! `fru_image.rs` for the contents.
//!
//! The EEPROM is only written if it is blank, or already partially holds the
//! image (for example after an interrupted run). Anything else is reported and
//! left alone. The result is reported with a line starting with `FMC EEPROM: `.

use core::panic::PanicInfo;
use ufmt::uwrite;
use ufmt::uwriteln;

use bittide_hal::hals::program_fmc_eeprom::DeviceInstances;
use bittide_hal::manual_additions::i2c_controller::I2cError;
use bittide_hal::manual_additions::timer::Duration;
use bittide_hal::shared_devices::{I2cController, Timer, Uart};

#[cfg(not(test))]
use riscv_rt::entry;

const INSTANCES: DeviceInstances = unsafe { DeviceInstances::new() };

/// FRU image, generated by `build.rs`
const FRU_IMAGE: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/fru.bin"));

/// PCA9544 I2C switch (U80) on the main I2C bus of the KCU105
const PCA9544_ADDRESS: u8 = 0x75;
/// PCA9544 control register value that enables channel 1: the FMC HPC I2C bus
const PCA9544_FMC_HPC: u8 = 0b100 | 1;

/// FMC EEPROMs are at 0x50 to 0x57, depending on the geographical address
/// pins of the FMC connector.
const EEPROM_ADDRESSES: core::ops::RangeInclusive<u8> = 0x50..=0x57;

/// Page size used for writes. Smaller than or equal to the page size of both the
/// 24LC128 (64 bytes) and the M24C32 (32 bytes) used on the TEF0008.
const PAGE_SIZE: usize = 16;

const MAX_RETRIES: usize = 5;

type Result<T> = core::result::Result<T, I2cError>;

/// Retry `f` when arbitration was lost to the system controller.
fn with_retries<T>(mut f: impl FnMut() -> Result<T>) -> Result<T> {
    let mut result = f();
    for _ in 0..MAX_RETRIES {
        if !matches!(result, Err(I2cError::ArbitrationLost)) {
            break;
        }
        result = f();
    }
    result
}

/// The EEPROM uses two address bytes.
fn read_eeprom(i2c: &I2cController, timer: &Timer, address: u8, buffer: &mut [u8]) -> Result<()> {
    with_retries(|| i2c.write_read(timer, address, &[0, 0], buffer))
}

/// Write a single page, then wait for the EEPROM to finish its write cycle.
fn write_page(
    i2c: &I2cController,
    timer: &Timer,
    address: u8,
    offset: usize,
    data: &[u8],
) -> Result<()> {
    let mut buffer = [0u8; 2 + PAGE_SIZE];
    buffer[0] = (offset >> 8) as u8;
    buffer[1] = offset as u8;
    buffer[2..2 + data.len()].copy_from_slice(data);
    with_retries(|| i2c.write(timer, address, &buffer[..2 + data.len()]))?;

    // The EEPROM does not acknowledge its address while it is writing.
    let deadline = timer.now() + Duration::from_millis(50);
    loop {
        if with_retries(|| i2c.probe(timer, address))? {
            return Ok(());
        }
        if timer.now() > deadline {
            return Err(I2cError::Timeout);
        }
    }
}

fn print_bytes(uart: &mut Uart, bytes: &[u8]) {
    for (i, byte) in bytes.iter().enumerate() {
        if i % 16 == 0 {
            uwrite!(uart, "  {:04X}:", i).unwrap();
        }
        uwrite!(uart, " {:02X}", *byte).unwrap();
        if i % 16 == 15 || i == bytes.len() - 1 {
            uwriteln!(uart, "").unwrap();
        }
    }
}

fn program(
    i2c: &I2cController,
    timer: &Timer,
    uart: &mut Uart,
) -> core::result::Result<&'static str, ()> {
    macro_rules! fail {
        ($($arg:tt)*) => {{
            uwrite!(uart, "FMC EEPROM: FAILED: ").unwrap();
            uwriteln!(uart, $($arg)*).unwrap();
            return Err(());
        }};
    }
    macro_rules! check {
        ($e:expr, $what:literal) => {
            match $e {
                Ok(v) => v,
                Err(e) => fail!("{}: {:?}", $what, e),
            }
        };
    }

    uwriteln!(uart, "FRU image ({} bytes):", FRU_IMAGE.len()).unwrap();
    print_bytes(uart, FRU_IMAGE);

    // Connect the FMC HPC I2C bus
    check!(
        with_retries(|| i2c.write(timer, PCA9544_ADDRESS, &[PCA9544_FMC_HPC])),
        "selecting the FMC HPC bus on the PCA9544"
    );
    // Disconnect the bus again below, also when programming fails
    let result = (|| {
        let mut control = [0u8];
        check!(
            with_retries(|| i2c.write_read(timer, PCA9544_ADDRESS, &[], &mut control)),
            "reading back the PCA9544"
        );
        // The upper nibble holds interrupt flags
        if control[0] & 0x07 != PCA9544_FMC_HPC {
            fail!("PCA9544 control register reads 0x{:02X}", control[0]);
        }

        // Find the EEPROM
        let mut eeprom = None;
        for address in EEPROM_ADDRESSES {
            if check!(
                with_retries(|| i2c.probe(timer, address)),
                "probing for the EEPROM"
            ) {
                uwriteln!(uart, "Found I2C target at 0x{:02X}", address).unwrap();
                if eeprom.is_some() {
                    fail!("multiple targets on the FMC I2C bus");
                }
                eeprom = Some(address);
            }
        }
        let Some(eeprom) = eeprom else {
            fail!("no EEPROM found, is an FMC card attached?");
        };

        // Check current contents
        let mut contents = [0u8; 256];
        let contents = &mut contents[..FRU_IMAGE.len()];
        check!(
            read_eeprom(i2c, timer, eeprom, contents),
            "reading the EEPROM"
        );
        uwriteln!(uart, "Current contents:").unwrap();
        print_bytes(uart, contents);

        if contents == FRU_IMAGE {
            return Ok("up to date");
        }
        let safe_to_write = contents
            .iter()
            .zip(FRU_IMAGE)
            .all(|(current, new)| *current == 0xFF || current == new);
        if !safe_to_write {
            fail!("EEPROM holds unknown data, not overwriting it");
        }

        // Write and verify
        uwriteln!(uart, "Writing FRU image").unwrap();
        for (page, data) in FRU_IMAGE.chunks(PAGE_SIZE).enumerate() {
            check!(
                write_page(i2c, timer, eeprom, page * PAGE_SIZE, data),
                "writing the EEPROM"
            );
        }
        check!(
            read_eeprom(i2c, timer, eeprom, contents),
            "reading back the EEPROM"
        );
        if contents != FRU_IMAGE {
            uwriteln!(uart, "Contents after writing:").unwrap();
            print_bytes(uart, contents);
            fail!("read back does not match the FRU image, is the EEPROM write protected?");
        }

        Ok("programmed")
    })();

    // Disconnect the FMC HPC I2C bus again, as found after power-on
    check!(
        with_retries(|| i2c.write(timer, PCA9544_ADDRESS, &[0])),
        "deselecting the FMC HPC bus on the PCA9544"
    );

    result
}

#[cfg_attr(not(test), entry)]
fn main() -> ! {
    let i2c = INSTANCES.i2c_controller;
    let timer = INSTANCES.timer;
    let mut uart = INSTANCES.uart;

    uwriteln!(uart, "Programming FMC EEPROM").unwrap();
    if let Ok(result) = program(&i2c, &timer, &mut uart) {
        uwriteln!(uart, "FMC EEPROM: {}", result).unwrap();
        uwriteln!(
            uart,
            "Power cycle the board for the new VADJ setting to take effect"
        )
        .unwrap();
    }

    loop {
        continue;
    }
}

#[panic_handler]
fn panic_handler(_info: &PanicInfo) -> ! {
    loop {
        continue;
    }
}
