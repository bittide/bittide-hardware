//! Programs the IPMI FRU EEPROM of the Trenz TEF0008 FMC card on the FMC HPC
//! connector of a KCU105. See `Bittide.Instances.Hitl.FmcEeprom` for why, and
//! `fru_image.rs` for the contents.
//!
//! The EEPROM is only written if it is blank, or already partially holds the
//! image (for example after an interrupted run). Anything else is reported and
//! left alone. The result is reported with a line starting with `FMC EEPROM: `.

use core::panic::PanicInfo;
use ufmt::uwrite;
use ufmt::uwriteln;

use bittide_hal::hals::program_fmc_eeprom::DeviceInstances;
use bittide_hal::manual_additions::i2c_controller::I2cError;
use bittide_hal::manual_additions::timer::Duration;
use bittide_hal::shared_devices::{I2cController, I2cLines, Timer, Uart};
use bittide_hal::types::{I2cCommand, I2cTransfer};
use clash_bindings::bitvector::BitVector;

#[cfg(not(test))]
use riscv_rt::entry;

const INSTANCES: DeviceInstances = unsafe { DeviceInstances::new() };

/// FRU image, generated by `build.rs`
const FRU_IMAGE: &[u8] = include_bytes!(concat!(env!("OUT_DIR"), "/fru.bin"));

/// PCA9544 I2C switch (U80) on the main I2C bus of the KCU105
const PCA9544_ADDRESS: u8 = 0x75;
/// PCA9544 control register value that enables channel 1: the FMC HPC I2C bus
const PCA9544_FMC_HPC: u8 = 0b100 | 1;

/// FMC EEPROMs are at 0x50 to 0x57, depending on the geographical address
/// pins of the FMC connector.
const EEPROM_ADDRESSES: core::ops::RangeInclusive<u8> = 0x50..=0x57;

/// Page size used for writes. Smaller than or equal to the page size of both the
/// 24LC128 (64 bytes) and the M24C32 (32 bytes) used on the TEF0008.
const PAGE_SIZE: usize = 16;

const MAX_RETRIES: usize = 5;

/// TMP: one-off, read-only test-drive. Dump the KCU105 board EEPROM and the FMC
/// EEPROM instead of programming the FMC EEPROM.
const DRY_RUN: bool = true;
/// PCA9544 control register value that enables channel 3: the KCU105 board EEPROM
const PCA9544_BOARD_EEPROM: u8 = 0b100 | 3;
/// KCU105 board EEPROM (U12, M24C08): 1 KiB in four 256 byte blocks at 0x54 to
/// 0x57. Uses a single address byte.
const BOARD_EEPROM_ADDRESS: u8 = 0x54;
/// Number of bytes of the FMC EEPROM to dump: the size of the smaller M24C32.
const FMC_DUMP_SIZE: usize = 4096;

type Result<T> = core::result::Result<T, I2cError>;

/// Retry `f` when arbitration was lost to the system controller.
fn with_retries<T>(mut f: impl FnMut() -> Result<T>) -> Result<T> {
    let mut result = f();
    for _ in 0..MAX_RETRIES {
        if !matches!(result, Err(I2cError::ArbitrationLost)) {
            break;
        }
        result = f();
    }
    result
}

/// The EEPROM uses two address bytes.
fn read_eeprom(i2c: &I2cController, timer: &Timer, address: u8, buffer: &mut [u8]) -> Result<()> {
    with_retries(|| i2c.write_read(timer, address, &[0, 0], buffer))
}

/// Write a single page, then wait for the EEPROM to finish its write cycle.
fn write_page(
    i2c: &I2cController,
    timer: &Timer,
    address: u8,
    offset: usize,
    data: &[u8],
) -> Result<()> {
    let mut buffer = [0u8; 2 + PAGE_SIZE];
    buffer[0] = (offset >> 8) as u8;
    buffer[1] = offset as u8;
    buffer[2..2 + data.len()].copy_from_slice(data);
    with_retries(|| i2c.write(timer, address, &buffer[..2 + data.len()]))?;

    // The EEPROM does not acknowledge its address while it is writing.
    let deadline = timer.now() + Duration::from_millis(50);
    loop {
        if with_retries(|| i2c.probe(timer, address))? {
            return Ok(());
        }
        if timer.now() > deadline {
            return Err(I2cError::Timeout);
        }
    }
}

fn print_bytes(uart: &mut Uart, bytes: &[u8]) {
    for (i, byte) in bytes.iter().enumerate() {
        if i % 16 == 0 {
            uwrite!(uart, "  {:04X}:", i).unwrap();
        }
        uwrite!(uart, " {:02X}", *byte).unwrap();
        if i % 16 == 15 || i == bytes.len() - 1 {
            uwriteln!(uart, "").unwrap();
        }
    }
}

/// Print `bytes` as a hex dump with an ASCII column, starting at `offset`.
fn print_dump(uart: &mut Uart, offset: usize, bytes: &[u8]) {
    for (row, line) in bytes.chunks(16).enumerate() {
        uwrite!(uart, "  {:04X}:", offset + row * 16).unwrap();
        for byte in line {
            uwrite!(uart, " {:02X}", *byte).unwrap();
        }
        uwrite!(uart, "  |").unwrap();
        for byte in line {
            let c = if byte.is_ascii_graphic() || *byte == b' ' {
                *byte as char
            } else {
                '.'
            };
            uwrite!(uart, "{}", c).unwrap();
        }
        uwriteln!(uart, "|").unwrap();
    }
}

/// Select a channel of the PCA9544 and read it back.
fn select_channel(i2c: &I2cController, timer: &Timer, control: u8) -> Result<bool> {
    with_retries(|| i2c.write(timer, PCA9544_ADDRESS, &[control]))?;
    let mut read_back = [0u8];
    with_retries(|| i2c.write_read(timer, PCA9544_ADDRESS, &[], &mut read_back))?;
    // The upper nibble holds interrupt flags
    Ok(read_back[0] & 0x07 == control)
}

/// TMP: print the state of the I2C bus, as seen by the I2C controller.
fn print_bus_state(uart: &mut Uart, i2c: &I2cController, lines: &I2cLines, what: &str) {
    uwriteln!(
        uart,
        "{}: bus_busy={} arbitration_lost={} scl_high={} sda_high={}",
        what,
        i2c.bus_busy(),
        i2c.arbitration_lost(),
        lines.scl_high(),
        lines.sda_high(),
    )
    .unwrap();
}

/// TMP: sample the I2C bus for a while, and print how often it was busy, and how
/// often SCL and SDA were low.
fn sample_bus(uart: &mut Uart, timer: &Timer, i2c: &I2cController, lines: &I2cLines) {
    let (mut samples, mut busy, mut scl_low, mut sda_low) = (0u32, 0u32, 0u32, 0u32);
    let deadline = timer.now() + Duration::from_millis(100);
    while timer.now() < deadline {
        samples += 1;
        busy += i2c.bus_busy() as u32;
        scl_low += !lines.scl_high() as u32;
        sda_low += !lines.sda_high() as u32;
    }
    uwriteln!(
        uart,
        "Sampled 100 ms: {} samples, bus_busy {}, SCL low {}, SDA low {}",
        samples,
        busy,
        scl_low,
        sda_low,
    )
    .unwrap();
}

/// TMP: send the address byte of a write to the PCA9544 as a single command, and
/// measure how long the controller takes to finish it. Then do the same for a STOP.
fn time_single_byte(uart: &mut Uart, timer: &Timer, i2c: &I2cController) {
    let commands = [
        (
            "Address byte",
            I2cCommand {
                start: true,
                transfer: I2cTransfer::WriteByte(BitVector::new([PCA9544_ADDRESS << 1]).unwrap()),
                stop: false,
            },
        ),
        (
            "STOP",
            I2cCommand {
                start: false,
                transfer: I2cTransfer::NoTransfer,
                stop: true,
            },
        ),
    ];
    for (what, command) in commands {
        let start = timer.now();
        let deadline = start + Duration::from_secs(1);
        i2c.set_command(command);
        i2c.set_commit(true);
        let mut finished = false;
        while timer.now() < deadline {
            if !i2c.commit() {
                finished = true;
                break;
            }
        }
        let elapsed = timer.now() - start;
        uwriteln!(
            uart,
            "{}: finished={} after {} us, ack_received={:?} arbitration_lost={} bus_busy={}",
            what,
            finished,
            elapsed.micros(),
            i2c.ack_received(),
            i2c.arbitration_lost(),
            i2c.bus_busy(),
        )
        .unwrap();
        if !finished {
            // The controller ignores new commands while busy
            break;
        }
    }
}

/// TMP: dump the KCU105 board EEPROM and the FMC EEPROM, without writing anything.
fn dry_run(
    i2c: &I2cController,
    timer: &Timer,
    uart: &mut Uart,
) -> core::result::Result<&'static str, ()> {
    macro_rules! fail {
        ($($arg:tt)*) => {{
            uwrite!(uart, "FMC EEPROM: FAILED: ").unwrap();
            uwriteln!(uart, $($arg)*).unwrap();
            return Err(());
        }};
    }
    macro_rules! check {
        ($e:expr, $what:literal) => {
            match $e {
                Ok(v) => v,
                Err(e) => fail!("{}: {:?}", $what, e),
            }
        };
    }

    let result = (|| {
        let mut block = [0u8; 256];

        // KCU105 board EEPROM: known, non-blank contents
        if !check!(
            select_channel(i2c, timer, PCA9544_BOARD_EEPROM),
            "selecting the board EEPROM bus on the PCA9544"
        ) {
            fail!("PCA9544 does not select the board EEPROM bus");
        }
        uwriteln!(uart, "Board EEPROM:").unwrap();
        for i in 0..4u8 {
            // A single address byte: a second one would be written as data
            check!(
                with_retries(|| i2c.write_read(timer, BOARD_EEPROM_ADDRESS + i, &[0], &mut block)),
                "reading the board EEPROM"
            );
            print_dump(uart, i as usize * block.len(), &block);
        }

        // FMC EEPROM
        if !check!(
            select_channel(i2c, timer, PCA9544_FMC_HPC),
            "selecting the FMC HPC bus on the PCA9544"
        ) {
            fail!("PCA9544 does not select the FMC HPC bus");
        }
        let mut eeprom = None;
        for address in EEPROM_ADDRESSES {
            if check!(
                with_retries(|| i2c.probe(timer, address)),
                "probing for the EEPROM"
            ) {
                uwriteln!(uart, "Found I2C target at 0x{:02X}", address).unwrap();
                eeprom = Some(address);
            }
        }
        let Some(eeprom) = eeprom else {
            fail!("no EEPROM found, is an FMC card attached?");
        };
        uwriteln!(uart, "FMC EEPROM at 0x{:02X}:", eeprom).unwrap();
        for offset in (0..FMC_DUMP_SIZE).step_by(block.len()) {
            let address_bytes = [(offset >> 8) as u8, offset as u8];
            check!(
                with_retries(|| i2c.write_read(timer, eeprom, &address_bytes, &mut block)),
                "reading the FMC EEPROM"
            );
            print_dump(uart, offset, &block);
        }

        Ok("dry run")
    })();

    // Disconnect the bus again, as found after power-on
    check!(
        with_retries(|| i2c.write(timer, PCA9544_ADDRESS, &[0])),
        "deselecting the bus on the PCA9544"
    );

    result
}

fn program(
    i2c: &I2cController,
    timer: &Timer,
    uart: &mut Uart,
) -> core::result::Result<&'static str, ()> {
    macro_rules! fail {
        ($($arg:tt)*) => {{
            uwrite!(uart, "FMC EEPROM: FAILED: ").unwrap();
            uwriteln!(uart, $($arg)*).unwrap();
            return Err(());
        }};
    }
    macro_rules! check {
        ($e:expr, $what:literal) => {
            match $e {
                Ok(v) => v,
                Err(e) => fail!("{}: {:?}", $what, e),
            }
        };
    }

    uwriteln!(uart, "FRU image ({} bytes):", FRU_IMAGE.len()).unwrap();
    print_bytes(uart, FRU_IMAGE);

    // Connect the FMC HPC I2C bus
    check!(
        with_retries(|| i2c.write(timer, PCA9544_ADDRESS, &[PCA9544_FMC_HPC])),
        "selecting the FMC HPC bus on the PCA9544"
    );
    // Disconnect the bus again below, also when programming fails
    let result = (|| {
        let mut control = [0u8];
        check!(
            with_retries(|| i2c.write_read(timer, PCA9544_ADDRESS, &[], &mut control)),
            "reading back the PCA9544"
        );
        // The upper nibble holds interrupt flags
        if control[0] & 0x07 != PCA9544_FMC_HPC {
            fail!("PCA9544 control register reads 0x{:02X}", control[0]);
        }

        // Find the EEPROM
        let mut eeprom = None;
        for address in EEPROM_ADDRESSES {
            if check!(
                with_retries(|| i2c.probe(timer, address)),
                "probing for the EEPROM"
            ) {
                uwriteln!(uart, "Found I2C target at 0x{:02X}", address).unwrap();
                if eeprom.is_some() {
                    fail!("multiple targets on the FMC I2C bus");
                }
                eeprom = Some(address);
            }
        }
        let Some(eeprom) = eeprom else {
            fail!("no EEPROM found, is an FMC card attached?");
        };

        // Check current contents
        let mut contents = [0u8; 256];
        let contents = &mut contents[..FRU_IMAGE.len()];
        check!(
            read_eeprom(i2c, timer, eeprom, contents),
            "reading the EEPROM"
        );
        uwriteln!(uart, "Current contents:").unwrap();
        print_bytes(uart, contents);

        if contents == FRU_IMAGE {
            return Ok("up to date");
        }
        let safe_to_write = contents
            .iter()
            .zip(FRU_IMAGE)
            .all(|(current, new)| *current == 0xFF || current == new);
        if !safe_to_write {
            fail!("EEPROM holds unknown data, not overwriting it");
        }

        // Write and verify
        uwriteln!(uart, "Writing FRU image").unwrap();
        for (page, data) in FRU_IMAGE.chunks(PAGE_SIZE).enumerate() {
            check!(
                write_page(i2c, timer, eeprom, page * PAGE_SIZE, data),
                "writing the EEPROM"
            );
        }
        check!(
            read_eeprom(i2c, timer, eeprom, contents),
            "reading back the EEPROM"
        );
        if contents != FRU_IMAGE {
            uwriteln!(uart, "Contents after writing:").unwrap();
            print_bytes(uart, contents);
            fail!("read back does not match the FRU image, is the EEPROM write protected?");
        }

        Ok("programmed")
    })();

    // Disconnect the FMC HPC I2C bus again, as found after power-on
    check!(
        with_retries(|| i2c.write(timer, PCA9544_ADDRESS, &[0])),
        "deselecting the FMC HPC bus on the PCA9544"
    );

    result
}

#[cfg_attr(not(test), entry)]
fn main() -> ! {
    let i2c = INSTANCES.i2c_controller;
    let timer = INSTANCES.timer;
    let mut uart = INSTANCES.uart;

    if DRY_RUN {
        let lines = INSTANCES.i2c_lines;
        uwriteln!(uart, "Reading EEPROMs (dry run)").unwrap();
        print_bus_state(&mut uart, &i2c, &lines, "Bus at start");
        sample_bus(&mut uart, &timer, &i2c, &lines);
        time_single_byte(&mut uart, &timer, &i2c);
        print_bus_state(&mut uart, &i2c, &lines, "Bus after single byte");
        match dry_run(&i2c, &timer, &mut uart) {
            Ok(result) => uwriteln!(uart, "FMC EEPROM: {}", result).unwrap(),
            Err(()) => {
                print_bus_state(&mut uart, &i2c, &lines, "Bus after failure");
                sample_bus(&mut uart, &timer, &i2c, &lines);
            }
        }
        loop {
            continue;
        }
    }

    uwriteln!(uart, "Programming FMC EEPROM").unwrap();
    if let Ok(result) = program(&i2c, &timer, &mut uart) {
        uwriteln!(uart, "FMC EEPROM: {}", result).unwrap();
        uwriteln!(
            uart,
            "Power cycle the board for the new VADJ setting to take effect"
        )
        .unwrap();
    }

    loop {
        continue;
    }
}

#[panic_handler]
fn panic_handler(_info: &PanicInfo) -> ! {
    loop {
        continue;
    }
}
